"""Splits the single ElevenLabs narration of the GTA reel into one clip per scene.

    python3 scripts/split-voiceover-gta.py public/voiceover/gta-original/marcos-the-agent-full.mp3

Each line below is (id, first speech second, last speech second, named cues). Times are seconds in the
full recording, found with ffmpeg silencedetect (-30 dB, 0.25 s) and checked by transcribing every
segment with Whisper. The cues are the moments the animation syncs to ("cura", "récord mundial"...).
Writes public/voiceover/gta/<id>.mp3 and src/ReelGta/voiceover.generated.ts
(clip durations and cue positions, both in frames at 30 fps, relative to the clip start).
"""

import json
import math
import subprocess
import sys
from pathlib import Path

FPS = 30
PRE, POST = 0.10, 0.18  # silence kept before / after the speech of each clip

LINES = [
    ("s01", 0.00, 6.28, {"miles": 1.28, "cura": 5.11}),
    ("s02", 6.80, 11.84, {"fecha": 7.89, "sale": 10.21}),
    ("s03", 12.22, 17.01, {"casi": 15.03}),
    ("s04", 17.36, 21.52, {"fingiendo": 20.39}),
    ("s05", 21.79, 25.17, {"jefe": 22.88, "hoy": 23.66, "risa": 24.95}),
    ("s06", 25.52, 28.88, {"colas": 26.70}),
    ("s07", 29.15, 35.73, {"ocho": 30.04, "mil": 33.35}),
    ("s08", 36.08, 40.38, {"sillas": 37.46}),
    ("s09", 40.78, 45.32, {"sale": 42.28, "numeros": 44.21}),
    ("s10", 45.82, 53.30, {"millon": 47.30, "mil": 50.17, "basura": 52.68}),
    ("s11", 53.73, 59.01, {"tose": 55.30, "gripe": 56.52, "vice": 57.51}),
    ("s12", 59.39, 64.21, {"vas": 60.01, "enfermar": 61.55, "leo": 63.00}),
]


def main() -> None:
    src = sys.argv[1]
    total = float(subprocess.check_output(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", src]).decode())
    out = Path("public/voiceover/gta")
    out.mkdir(parents=True, exist_ok=True)
    frames, cues = {}, {}
    for line_id, first, last, named in LINES:
        start = max(0.0, first - PRE)
        end = min(total, last + POST)
        dur = end - start
        mp3 = out / f"{line_id}.mp3"
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-ss", f"{start:.3f}", "-t", f"{dur:.3f}", "-i", src,
             "-af", f"afade=t=in:d=0.01,afade=t=out:st={dur - 0.05:.3f}:d=0.05",
             "-ar", "44100", "-b:a", "160k", str(mp3)],
            check=True,
        )
        frames[line_id] = math.ceil(dur * FPS)
        cues[line_id] = {k: round((t - start) * FPS) for k, t in named.items()}
        print(f"{line_id}  {start:6.2f}-{end:6.2f}  {dur:5.2f}s  cues {cues[line_id]}")
    Path("src/ReelGta/voiceover.generated.ts").write_text(
        "// Generated by scripts/split-voiceover-gta.py — do not edit by hand.\n"
        f"export const VOICE_FRAMES = {json.dumps(frames, indent=2)} as const;\n\n"
        "/** Moments inside each clip the animation syncs to, in frames from the clip start. */\n"
        f"export const VOICE_CUES = {json.dumps(cues, indent=2)} as const;\n"
    )
    print("Wrote src/ReelGta/voiceover.generated.ts")


if __name__ == "__main__":
    main()
