"""Cut one full voiceover take (e.g. an ElevenLabs download) into per-line clips.

    python3 scripts/split-voiceover.py guiones/reel-diamante-natural.voz.json \
        public/voiceover/diamante src/ReelDiamante/voiceover.generated.ts

The JSON lists, per line id, its phrases as [start_s, end_s, text]. Each line
clip runs from its first phrase start to its last phrase end. The generated TS
has VOICE_FRAMES (clip length) and PHRASES (phrase frames relative to the clip),
so captions and sound effects can hit each word.
"""

import json
import math
import subprocess
import sys
from pathlib import Path

FPS = 30
PAD_IN, PAD_OUT = 0.04, 0.12


def main() -> None:
    spec_path, out_dir, ts_path = sys.argv[1:4]
    spec = json.loads(Path(spec_path).read_text())
    src = spec["source"]
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    # One gain for the whole take (keeps the actor's dynamics), aiming at -15 LUFS.
    meter = subprocess.run(["ffmpeg", "-i", src, "-af", "ebur128", "-f", "null", "-"],
                           capture_output=True, text=True).stderr
    integrated = float(meter.rsplit("I:", 1)[1].split("LUFS")[0])
    gain = -15.0 - integrated
    print(f"take loudness {integrated:.1f} LUFS -> gain {gain:+.1f} dB")
    frames, phrases = {}, {}
    for line_id, items in spec["phrases"].items():
        start = max(0.0, items[0][0] - PAD_IN)
        end = items[-1][1] + PAD_OUT
        mp3 = out / f"{line_id}.mp3"
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-ss", f"{start:.3f}", "-to", f"{end:.3f}", "-i", src,
             "-af", f"volume={gain:.2f}dB,alimiter=limit=0.89,afade=t=in:d=0.02,areverse,afade=t=in:d=0.04,areverse",
             "-ar", "44100", "-b:a", "192k", str(mp3)],
            check=True,
        )
        frames[line_id] = math.ceil((end - start) * FPS)
        phrases[line_id] = [[round((a - start) * FPS), round((b - start) * FPS), t] for a, b, t in items]
        print(f"{line_id:4} {end - start:5.2f}s  {' '.join(p[2] for p in items)}")
    Path(ts_path).write_text(
        f"// Generated by scripts/split-voiceover.py from {spec_path} — do not edit by hand.\n"
        f"export const VOICE_FRAMES = {json.dumps(frames, indent=2)} as const;\n\n"
        f"/** [startFrame, endFrame, text] of each phrase, relative to the line clip. */\n"
        f"export const PHRASES: Record<keyof typeof VOICE_FRAMES, [number, number, string][]> = "
        f"{json.dumps(phrases, indent=2, ensure_ascii=False)};\n"
    )
    print(f"Wrote {ts_path}")


if __name__ == "__main__":
    main()
