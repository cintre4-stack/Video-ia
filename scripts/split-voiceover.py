"""Split one full narration file into per-line clips for a reel.

    python3 scripts/split-voiceover.py <full.mp3> <cuts.json> <out_dir> <voiceover.generated.ts>

cuts.json: {"s01": [start, end], ...} in seconds (cut on the pauses between lines).
Writes <out_dir>/<id>.mp3 and the VOICE_FRAMES file the composition uses.
"""

import json
import math
import subprocess
import sys
from pathlib import Path

FPS = 30


def main() -> None:
    src, cuts_path, out_dir, ts_path = sys.argv[1:5]
    cuts = json.loads(Path(cuts_path).read_text())
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    frames = {}
    for line_id, (start, end) in cuts.items():
        mp3 = out / f"{line_id}.mp3"
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-ss", f"{max(0, start - 0.04):.3f}", "-to", f"{end + 0.08:.3f}", "-i", src,
             "-af", "afade=t=in:d=0.02,areverse,afade=t=in:d=0.06,areverse,loudnorm=I=-16:TP=-1.5:LRA=11",
             "-ar", "44100", "-b:a", "192k", str(mp3)],
            check=True,
        )
        seconds = float(subprocess.check_output(
            ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(mp3)]).decode())
        frames[line_id] = math.ceil(seconds * FPS)
        print(f"{line_id:4} {seconds:5.2f}s")
    Path(ts_path).write_text(
        f"// Generated by scripts/split-voiceover.py from {src} — do not edit by hand.\n"
        f"export const VOICE_FRAMES = {json.dumps(frames, indent=2)} as const;\n"
    )


if __name__ == "__main__":
    main()
