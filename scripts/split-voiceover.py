"""Split a single-take narration MP3 into per-line clips at its longest pauses.

    python3 scripts/split-voiceover.py take.mp3 <lines> <out_dir> <voiceover.generated.ts>

Finds pauses with ffmpeg silencedetect, cuts at the middle of the (lines-1)
longest ones, trims and normalizes each clip to s01.mp3, s02.mp3, ... and
writes the clip lengths (frames at 30 fps) for the composition.
"""

import json
import math
import re
import subprocess
import sys
from pathlib import Path

FPS = 30
FILTER = (
    "silenceremove=start_periods=1:start_threshold=-45dB,"
    "areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,"
    "loudnorm=I=-16:TP=-1.5:LRA=9"
)


def main() -> None:
    src, n, out_dir, ts_path = sys.argv[1], int(sys.argv[2]), Path(sys.argv[3]), sys.argv[4]
    log = subprocess.run(
        ["ffmpeg", "-i", src, "-af", "silencedetect=noise=-35dB:d=0.25", "-f", "null", "-"],
        capture_output=True, text=True,
    ).stderr
    starts = [float(x) for x in re.findall(r"silence_start: ([\d.]+)", log)]
    ends = [float(x) for x in re.findall(r"silence_end: ([\d.]+)", log)]
    gaps = sorted(zip(starts, ends), key=lambda g: g[1] - g[0], reverse=True)[: n - 1]
    if len(gaps) < n - 1:
        sys.exit(f"Only {len(gaps)} pauses found, need {n - 1}")
    cuts = sorted((a + b) / 2 for a, b in gaps)
    total = float(subprocess.check_output(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", src]).decode())
    bounds = [0.0, *cuts, total]
    out_dir.mkdir(parents=True, exist_ok=True)
    frames = {}
    for i in range(n):
        line_id = f"s{i + 1:02d}"
        mp3 = out_dir / f"{line_id}.mp3"
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", str(bounds[i]), "-to", str(bounds[i + 1]),
                        "-i", src, "-af", FILTER, "-ar", "44100", "-b:a", "160k", str(mp3)], check=True)
        sec = float(subprocess.check_output(
            ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(mp3)]).decode())
        frames[line_id] = math.ceil(sec * FPS)
        print(f"{line_id}  {bounds[i]:6.2f}-{bounds[i + 1]:6.2f}s  -> {sec:5.2f}s")
    Path(ts_path).write_text(
        f"// Generated by scripts/split-voiceover.py from {Path(src).name} — do not edit by hand.\n"
        f"export const VOICE_FRAMES = {json.dumps(frames, indent=2)} as const;\n"
    )
    print(f"Wrote {ts_path}")


if __name__ == "__main__":
    main()
