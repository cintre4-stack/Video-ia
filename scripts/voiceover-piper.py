"""Generic offline voiceover with Piper TTS, driven by a guion JSON file.

    python3 scripts/voiceover-piper.py <model.onnx> guiones/reel-anfield-2019.json \
        public/voiceover/anfield src/ReelAnfield/voiceover.generated.ts

The JSON has "lines": [[id, text], ...] and optional "speed": {id: length_scale}.
See scripts/generate-voiceover-piper.py for how to install Piper and the voice.
"""

import json
import math
import subprocess
import sys
from pathlib import Path
import tempfile

FPS = 30
FILTER = (
    "aresample=44100,highpass=f=90,"
    "equalizer=f=3000:t=q:w=1.2:g=4,equalizer=f=250:t=q:w=1:g=-2,"
    "acompressor=threshold=-20dB:ratio=3:attack=5:release=80,"
    "loudnorm=I=-16:TP=-1.5:LRA=7,"
    "silenceremove=start_periods=1:start_threshold=-45dB,"
    "areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse"
)


def main() -> None:
    model, guion, out_dir, ts_path = sys.argv[1:5]
    data = json.loads(Path(guion).read_text())
    speed = data.get("speed", {})
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    frames = {}
    with tempfile.TemporaryDirectory() as tmp:
        for line_id, text in data["lines"]:
            wav = Path(tmp) / f"{line_id}.wav"
            subprocess.run(
                [sys.executable, "-m", "piper", "-m", model, "-f", str(wav),
                 "--length-scale", str(speed.get(line_id, 0.9)), "--sentence-silence", "0.15"],
                input=text.encode(), check=True, capture_output=True,
            )
            mp3 = out / f"{line_id}.mp3"
            subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(wav), "-af", FILTER,
                            "-ar", "44100", "-b:a", "160k", str(mp3)], check=True)
            seconds = float(subprocess.check_output(
                ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(mp3)]).decode())
            frames[line_id] = math.ceil(seconds * FPS)
            print(f"{line_id:5} {seconds:5.2f}s  {text}")
    Path(ts_path).parent.mkdir(parents=True, exist_ok=True)
    Path(ts_path).write_text(
        f"// Generated by scripts/voiceover-piper.py from {guion} — do not edit by hand.\n"
        f"export const VOICE_FRAMES = {json.dumps(frames, indent=2)} as const;\n"
    )
    print(f"Wrote {ts_path}")


if __name__ == "__main__":
    main()
