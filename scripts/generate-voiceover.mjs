// Generates the Spanish voiceover for the 93:20 reel with ElevenLabs TTS.
//
//   ELEVENLABS_API_KEY=... node scripts/generate-voiceover.mjs [voiceId]
//
// Writes public/voiceover/reel9320/<id>.mp3 and src/Reel9320/voiceover.generated.ts
// (clip durations in frames), which the composition uses to size each scene.
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";

const FPS = 30;
const VOICE_ID = process.argv[2] ?? process.env.ELEVENLABS_VOICE_ID;
const KEY = process.env.ELEVENLABS_API_KEY;
if (!VOICE_ID || !KEY) {
  console.error("Usage: ELEVENLABS_API_KEY=... node scripts/generate-voiceover.mjs <voiceId>");
  process.exit(1);
}

// Keep in sync with guiones/reel-aguero-9320-narracion.md
const LINES = [
  ["s01", "Minuto noventa y tres, segundo veinte. El momento que cambió Manchester para siempre."],
  ["s02", "Trece de mayo de dos mil doce. Última jornada. City y United, empatados a puntos. El City solo manda por diferencia de goles."],
  ["s03", "En Sunderland golpea primero el United. Gol de Rooney. Ahora mismo, el título es rojo."],
  ["s04", "Pero el City responde. ¡Zabaleta! Uno a cero. El título vuelve a ser azul."],
  ["s05", "Y entonces, el desastre. Empata Cissé. Expulsan a Barton... y aun así, con diez, Mackie hace el uno a dos."],
  ["s06", "Minuto noventa. Cinco de descuento. El City está muerto."],
  ["s07", "Dzeko, de cabeza. ¡Dos a dos! Pero el empate... no sirve de nada."],
  ["s08", "En Sunderland ya ha terminado. Los jugadores del United esperan en el césped. Se creen campeones."],
  ["s09a", "Última jugada. Agüero para Balotelli... Balotelli, cayendo, se la devuelve..."],
  ["s09b", "¡Agüeroooo! ¡El City es campeón!"],
  ["s10", "Mismos puntos. Ocho goles de diferencia. Primera liga del City en cuarenta y cuatro años."],
  ["s11", "¿Y tú, dónde estabas en el noventa y tres veinte? Cuéntamelo en comentarios."],
];

const outDir = "public/voiceover/reel9320";
mkdirSync(outDir, { recursive: true });

const frames = {};
let previous = "";
for (const [id, text] of LINES) {
  const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}?output_format=mp3_44100_128`, {
    method: "POST",
    headers: { "xi-api-key": KEY, "Content-Type": "application/json", Accept: "audio/mpeg" },
    body: JSON.stringify({
      text,
      model_id: "eleven_multilingual_v2",
      language_code: "es",
      previous_text: previous || undefined,
      voice_settings: { stability: 0.38, similarity_boost: 0.8, style: 0.55, use_speaker_boost: true },
    }),
  });
  if (!res.ok) {
    console.error(id, res.status, await res.text());
    process.exit(1);
  }
  const file = `${outDir}/${id}.mp3`;
  writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  const seconds = Number(
    execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file]).toString(),
  );
  frames[id] = Math.ceil(seconds * FPS);
  previous = text;
  console.log(`${id}  ${seconds.toFixed(2)}s  ${text}`);
}

writeFileSync(
  "src/Reel9320/voiceover.generated.ts",
  `// Generated by scripts/generate-voiceover.mjs — do not edit by hand.\n` +
    `export const VOICE_FRAMES = ${JSON.stringify(frames, null, 2)} as const;\n`,
);
console.log("Wrote src/Reel9320/voiceover.generated.ts");
