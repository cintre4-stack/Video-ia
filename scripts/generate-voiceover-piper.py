"""Offline Spanish voiceover for the 93:20 reel using Piper TTS (free, no API key).

Setup (once):
    pip install piper-tts==1.8.0
    curl -L https://github.com/rhasspy/piper/releases/download/v0.0.2/voice-es-carlfm-x-low.tar.gz | tar xz -C <dir>

Run from the repo root:
    python3 scripts/generate-voiceover-piper.py <dir>/es-carlfm-x-low.onnx

Writes public/voiceover/reel9320/<id>.mp3 and src/Reel9320/voiceover.generated.ts,
the same outputs as scripts/generate-voiceover.mjs (ElevenLabs), so the composition
works with either engine.
"""

import json
import math
import subprocess
import sys
import tempfile
from pathlib import Path

FPS = 30
MODEL = sys.argv[1] if len(sys.argv) > 1 else "es-carlfm-x-low.onnx"
OUT = Path("public/voiceover/reel9320")

# Spanish phonetic spelling of English names, because Piper reads letters the
# Spanish way ("City" would come out with a Castilian "th").
# Keep in sync with guiones/reel-aguero-9320-narracion.md
LINES = [
    ("s01", "Minuto noventa y tres, segundo veinte. El momento que cambió Mánchester para siempre."),
    ("s02", "Trece de mayo de dos mil doce. Última jornada. Siti y Iunáited, empatados a puntos. El Siti solo manda por diferencia de goles."),
    ("s03", "En Sánderland golpea primero el Iunáited. ¡Gol de Runi! Ahora mismo, el título es rojo."),
    ("s04", "Pero el Siti responde. ¡Zabaleta! Uno a cero. El título vuelve a ser azul."),
    ("s05", "Y entonces, el desastre. Empata Sisé. Expulsan a Barton. Y aun así, con diez, Maki hace el uno a dos."),
    ("s06", "Minuto noventa. Cinco de descuento. El Siti está muerto."),
    ("s07", "Dyeko, de cabeza. ¡Dos a dos! Pero el empate, no sirve de nada."),
    ("s08", "En Sánderland ya ha terminado. Los jugadores del Iunáited esperan en el césped. Se creen campeones."),
    ("s09a", "Última jugada. Balotelli, desde el suelo, para Agüero."),
    ("s09b", "¡Agüero! ¡Agüero! ¡El Siti es campeón!"),
    ("s10", "Mismos puntos. Ocho goles de diferencia. Primera liga del Siti en cuarenta y cuatro años."),
    ("s11", "¿Y tú, dónde estabas en el noventa y tres veinte? Cuéntamelo en comentarios."),
]

# Faster, livelier delivery for the goal lines.
SPEED = {"s09a": 0.85, "s09b": 0.8, "s04": 0.85, "s07": 0.85}

# Broadcast-style polish for a 16 kHz model: upsample, cut rumble, add presence,
# compress, then normalize loudness to -16 LUFS (social media standard).
FILTER = (
    "aresample=44100,highpass=f=90,"
    "equalizer=f=3000:t=q:w=1.2:g=4,equalizer=f=250:t=q:w=1:g=-2,"
    "acompressor=threshold=-20dB:ratio=3:attack=5:release=80,"
    "loudnorm=I=-16:TP=-1.5:LRA=7,"
    "silenceremove=start_periods=1:start_threshold=-45dB,"
    "areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse"
)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    frames = {}
    with tempfile.TemporaryDirectory() as tmp:
        for line_id, text in LINES:
            wav = Path(tmp) / f"{line_id}.wav"
            subprocess.run(
                [
                    sys.executable, "-m", "piper", "-m", MODEL, "-f", str(wav),
                    "--length-scale", str(SPEED.get(line_id, 0.9)),
                    "--sentence-silence", "0.15",
                ],
                input=text.encode(), check=True, capture_output=True,
            )
            mp3 = OUT / f"{line_id}.mp3"
            subprocess.run(
                ["ffmpeg", "-v", "error", "-y", "-i", str(wav), "-af", FILTER,
                 "-ar", "44100", "-b:a", "160k", str(mp3)],
                check=True,
            )
            seconds = float(subprocess.check_output(
                ["ffprobe", "-v", "error", "-show_entries", "format=duration",
                 "-of", "csv=p=0", str(mp3)]).decode())
            frames[line_id] = math.ceil(seconds * FPS)
            print(f"{line_id:5} {seconds:5.2f}s  {text}")

    Path("src/Reel9320/voiceover.generated.ts").write_text(
        "// Generated by scripts/generate-voiceover-piper.py — do not edit by hand.\n"
        f"export const VOICE_FRAMES = {json.dumps(frames, indent=2)} as const;\n"
    )
    print("Wrote src/Reel9320/voiceover.generated.ts")


if __name__ == "__main__":
    main()
