"""Per-frame loudness (0..1) of each voice clip, for lip-sync.

    python3 scripts/voice-envelope.py public/voiceover/club src/ReelClub/envelope.generated.ts
"""
import json, subprocess, sys
from pathlib import Path
import numpy as np

FPS, SR = 30, 22050
src, out = Path(sys.argv[1]), Path(sys.argv[2])
env = {}
for mp3 in sorted(src.glob("*.mp3")):
    raw = subprocess.check_output(["ffmpeg", "-v", "error", "-i", str(mp3), "-ac", "1", "-ar", str(SR), "-f", "s16le", "-"])
    x = np.frombuffer(raw, dtype=np.int16).astype(np.float32) / 32768
    hop = SR // FPS
    n = len(x) // hop + 1
    rms = np.array([np.sqrt(np.mean(x[i * hop:(i + 1) * hop] ** 2)) if len(x[i * hop:(i + 1) * hop]) else 0 for i in range(n)])
    rms = np.clip(rms / (np.percentile(rms, 95) + 1e-6), 0, 1)
    env[mp3.stem] = [round(float(v), 2) for v in rms]
out.write_text(f"// Generated by scripts/voice-envelope.py — do not edit by hand.\nexport const VOICE_ENV: Record<string, number[]> = {json.dumps(env)};\n")
print("wrote", out, {k: len(v) for k, v in env.items()})
