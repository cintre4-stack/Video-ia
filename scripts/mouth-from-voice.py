"""Per-frame mouth openness (0..1) from voiceover clips, for lip-sync.

    python3 scripts/mouth-from-voice.py public/voiceover/lasana src/ReelLasagna/mouth.generated.ts
"""

import json
import math
import struct
import subprocess
import sys
from pathlib import Path

FPS = 30
RATE = 16000


def envelope(path: Path) -> list[float]:
    raw = subprocess.check_output(
        ["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(RATE), "-f", "s16le", "-"]
    )
    samples = struct.unpack(f"<{len(raw) // 2}h", raw)
    hop = RATE // FPS
    rms = []
    for i in range(0, len(samples), hop):
        chunk = samples[i : i + hop]
        rms.append(math.sqrt(sum(s * s for s in chunk) / max(1, len(chunk))) / 32768)
    peak = sorted(rms)[int(len(rms) * 0.95)] or 1
    out, prev = [], 0.0
    for v in rms:
        x = min(1.0, (v / peak) ** 0.8)
        x = 0.0 if x < 0.08 else x
        prev = prev * 0.35 + x * 0.65  # suavizado ligero
        out.append(round(prev, 2))
    return out


def main() -> None:
    src, ts = sys.argv[1:3]
    data = {p.stem: envelope(p) for p in sorted(Path(src).glob("*.mp3"))}
    Path(ts).write_text(
        f"// Generated by scripts/mouth-from-voice.py from {src} — do not edit by hand.\n"
        f"export const MOUTH: Record<string, number[]> = {json.dumps(data, separators=(',', ':'))};\n"
    )
    print(f"Wrote {ts}: " + ", ".join(f"{k}={len(v)}" for k, v in data.items()))


if __name__ == "__main__":
    main()
